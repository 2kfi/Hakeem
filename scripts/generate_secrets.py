"""
Hakeem Secret Generator

Generate cryptographically secure secrets for all services.
Supports interactive mode (prompts with defaults) and random mode.

Usage:
  python scripts/generate_secrets.py              # Interactive
  python scripts/generate_secrets.py --random      # Generate all, print summary
  python scripts/generate_secrets.py --random --stdout  # Print as .env format
  python scripts/generate_secrets.py --random --format=yaml  # Print as YAML
"""

import argparse
