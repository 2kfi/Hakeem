def write_infra_compose(path: Path, db_password: str) -> None:
    content = path.read_text()
    old = 'NEO4J_AUTH=neo4j/69397516'
    new = f'NEO4J_AUTH=neo4j/{db_password}'
    if old in content:
        content = content.replace(old, new)
    path.write_text(content)


def generate_interactive() -> None:
    print("\nHakeem Secret Generator".center(50, "="))
    print("  Press Enter to accept the auto-generated default,")
    print("  or type your own value.\n")

    jwt_secret = prompt("JWT Secret", random_hex(32))
    db_password = prompt("DB Password (Redis / Neo4j / Qdrant)", random_password(16))
    llm_api_key = prompt("LLM API Key (leave empty to skip)", "", secret=False)

    print("\n" + "=" * 50)
    print("Generated Secrets Summary")
    print("=" * 50)
    print(f"  JWT_SECRET:     {jwt_secret}")
    print(f"  DB_PASSWORD:    {db_password}")
    print(f"  LLM_API_KEY:    {llm_api_key or '(not set)'}")
    print()

    if input("Write to .env? (y/N): ").strip().lower() == "y":
        env_data = {
            "JWT_SECRET": jwt_secret,
            "DB_PASSWORD": db_password,
            "REDIS_PASSWORD": db_password,
            "NEO4J_PASSWORD": db_password,
        }
        if llm_api_key:
            env_data["LLM_API_KEY"] = llm_api_key
        write_env(
            REPO_ROOT / ".env",
            env_data,
            header="# Hakeem Backend — Generated Secrets\n# Generated by scripts/generate_secrets.py\n# Do NOT commit this file.\n",
        )
        print("  ✓ .env written")

    if input("Write to config.yaml? (y/N): ").strip().lower() == "y":
        write_config_yaml(REPO_ROOT / "config.yaml", db_password, jwt_secret)
        print("  ✓ config.yaml written")

    if input("Update docker-compose.infra.yml? (y/N): ").strip().lower() == "y":
        write_infra_compose(REPO_ROOT / "docker-compose.infra.yml", db_password)
        print("  ✓ docker-compose.infra.yml updated")

    print("\nDone.")

    if not llm_api_key:
        print("\n⚠  Remember to set LLM_API_KEY in .env before running.")


def generate_random(args: argparse.Namespace) -> None:
    jwt_secret = random_hex(32)
    db_password = random_password(16)

    if args.stdout or args.format:
        fmt = args.format or "env"
        if fmt == "env":
            print(f"JWT_SECRET={jwt_secret}")
            print(f"DB_PASSWORD={db_password}")
            print(f"REDIS_PASSWORD={db_password}")
            print(f"NEO4J_PASSWORD={db_password}")
        elif fmt == "yaml":
            print(f'jwt:')
            print(f'  secret: "{jwt_secret}"')
            print(f'redis:')
            print(f'  password: "{db_password}"')
            print(f'  url: "redis://:{db_password}@localhost:6379/0"')
        return

    env_data = {
        "JWT_SECRET": jwt_secret,
        "DB_PASSWORD": db_password,
        "REDIS_PASSWORD": db_password,
        "NEO4J_PASSWORD": db_password,
    }

    write_env(
        REPO_ROOT / ".env",
        env_data,
        header="# Hakeem Backend — Generated Secrets\n# Generated by scripts/generate_secrets.py\n# Do NOT commit this file.\n",
    )
    write_config_yaml(REPO_ROOT / "config.yaml", db_password, jwt_secret)
    write_infra_compose(REPO_ROOT / "docker-compose.infra.yml", db_password)

    print("=" * 50)
    print("Hakeem Secrets Generated")
    print("=" * 50)
    print(f"  JWT_SECRET:     {jwt_secret}")
    print(f"  DB_PASSWORD:    {db_password}    (Redis / Neo4j / Qdrant)")
    print()
    print("  Written to:")
    print("    ✓ .env")
    print("    ✓ config.yaml")
    print("    ✓ docker-compose.infra.yml")
    print()
    print("⚠  LLM_API_KEY was not set — add it to .env manually.")
    print("⚠  config.yaml and .env are now in .gitignore — they won't be committed.")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate secrets for Hakeem Backend")
    parser.add_argument("--random", action="store_true", help="Generate all secrets non-interactively")
    parser.add_argument("--stdout", action="store_true", help="Print secrets to stdout (implies --random)")
    parser.add_argument("--format", choices=["env", "yaml"], default=None, help="Output format for --stdout")
    args = parser.parse_args()

    if args.stdout:
        args.random = True
        args.format = args.format or "env"

    if args.random:
        generate_random(args)
    else:
        generate_interactive()


if __name__ == "__main__":
    main()
