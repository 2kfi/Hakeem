import string
import sys
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parent.parent


def random_hex(nbytes: int = 32) -> str:
    return secrets.token_hex(nbytes)


def random_password(length: int = 16) -> str:
    alphabet = string.ascii_letters + string.digits
    return "".join(secrets.choice(alphabet) for _ in range(length))


def random_urlsafe(length: int = 24) -> str:
    return secrets.token_urlsafe(length)


def prompt(label: str, default: str, secret: bool = True) -> str:
    display = default[:12] + "..." if secret and len(default) > 12 else default
    prompt_str = f"  {label} [{display}]: "
    val = input(prompt_str).strip()
    if not val:
        return default
    return val


def write_env(path: Path, data: dict[str, str], header: str = "") -> None:
    lines = []
    if header:
        lines.append(header)
    for k, v in data.items():
        lines.append(f'{k}={v}')
    lines.append("")
    path.write_text("\n".join(lines))


